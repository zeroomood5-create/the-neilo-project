import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_PACKAGE || 'playwright');
const browser=await chromium.launch({channel:'chrome',headless:true});
try{
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://localhost:4173/');
  await page.getByRole('button',{name:'Play adventure'}).click();
  const video=page.locator('video');
  await page.waitForFunction(()=>document.querySelector('video')?.currentTime>.2);
  await page.locator('[data-cinema="pause"]').click();
  const paused=await video.evaluate(v=>v.currentTime);
  await page.waitForTimeout(400);
  assert.ok(Math.abs(await video.evaluate(v=>v.currentTime)-paused)<.1,'Paused video keeps advancing');
  await page.locator('[data-cinema="pause"]').click();
  await page.waitForFunction(t=>document.querySelector('video')?.currentTime>t+.2,paused);
  await page.locator('[data-cinema="next"]').click();
  assert.match(await page.locator('video').getAttribute('src'),/harness/);
  await page.locator('[data-cinema="skip"]').click();
  await page.locator('[data-action="guide-done"]').click();
  await page.locator('canvas[data-assets="ready"]').waitFor();
  const canvas=page.locator('canvas');const b=await canvas.boundingBox();
  await canvas.click({position:{x:b.width*.83,y:b.height*.86}});
  await page.waitForFunction(()=>document.querySelector('canvas').dataset.motion==='walking');
  const seen=new Set();
  for(let i=0;i<7;i++){seen.add(await canvas.getAttribute('data-walk-frame'));await page.waitForTimeout(90)}
  assert.ok(seen.size>=4,'Walk cycle did not advance through distinct frames');
  await page.screenshot({path:'qa/motion-v2.png'});
  await page.waitForFunction(()=>document.querySelector('canvas').dataset.motion==='idle');
  await page.getByRole('button',{name:'A little blue light',exact:true}).click();
  assert.match(await page.locator('video').getAttribute('src'),/discover/);
  await page.locator('[data-cinema="next"]').click();
  assert.match(await page.locator('video').getAttribute('src'),/wake/);
  await page.locator('[data-cinema="skip"]').click();
  await page.getByRole('button',{name:'Can we reach my crew?'}).click();
  await page.locator('[data-action="guide-done"]').click();
  await page.locator('canvas[data-assets="ready"]').waitFor();
  const b2=await canvas.boundingBox();
  await canvas.click({position:{x:b2.width*.22,y:b2.height*.88}});
  await page.waitForTimeout(400);
  await page.screenshot({path:'qa/companions-motion-v2.png'});
  await page.waitForFunction(()=>document.querySelector('canvas').dataset.motion==='idle');
  await page.getByRole('button',{name:'Go to mission control'}).click();
  assert.equal(await page.locator('[data-hotspot="power"]').getAttribute('data-state'),'active');
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await page.locator('[data-hotspot="power"]').evaluate(el=>getComputedStyle(el,'::before').animationName),'none');
  await page.goto('http://localhost:4173/review.html');
  await page.locator('audio').first().waitFor();
  assert.equal(await page.locator('audio').count(),3);
  assert.equal(await page.locator('video').count(),6);
  await page.screenshot({path:'qa/team-review.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('PASS · video playback/pause/resume, discovery sequence, live walk frames, robot companion, station state, reduced motion, voice review.');
}finally{await browser.close()}
